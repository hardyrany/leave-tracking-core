package com.hardy.leavetracking.employee.domain.enums;

/**
 * Enumeração que representa os departamentos disponíveis na empresa.
 * Utilizada para categorizar os funcionários e validar os seus dados.
 */
public enum Department {

    /**
     * Departamento Comercial / Vendas.
     */
    SALES,

    /**
     * Departamento de Marketing e Comunicação.
     */
    MARKETING,

    /**
     * Departamento de Engenharia.
     */
    ENGINEERING,

    /**
     * Departamento de Recursos Humanos.
     */
    HR,

    /**
     * Departamento Financeiro.
     */
    FINANCE,

    /**
     * Departamento de Tecnologias de Informação.
     */
    IT,

    /**
     * Departamento Jurídico.
     */
    LEGAL,

    /**
     * Departamento de Retalho.
     */
    RETAIL,

    /**
     * Departamento de Cadeia de Abastecimento.
     */
    SUPPLY_CHAIN,

    /**
     * Departamento de Logística.
     */
    LOGISTICS
}